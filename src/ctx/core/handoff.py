"""Deterministic handoff brief (M3): state, decisions, open threads, recent files/commands.

Extractive: no LLM. The evidence is the newest events of a project (or of every allowed
project) selected by `build_context` with an empty query (rule 8); every line carries the
`[E<event id>]` it came from. The same events always give byte-identical output (nothing
time-of-day dependent is printed), so briefs can be diffed. `--llm` rewrites the same
package through `ctx.llm.grounded`; this module never calls a model.
"""

import re
import sqlite3
from collections import Counter
from datetime import UTC, datetime

from ctx.core.context import ContextItem, ContextPackage, build_context
from ctx.core.episodes import tool_targets
from ctx.core.redact import redact
from ctx.core.search import resolve_project

TARGETS = ("claude-code", "codex", "generic")
DEFAULT_BUDGET = 6000
MAX_ITEMS = 300
MAX_BULLETS = 8
LINE_CHARS = 240
_DECISION = re.compile(
    r"\b(decid(?:ed|e|ing)|decision|we(?:'ll| will) (?:use|go with)|going with|settled on|"
    r"chose|chosen|instead of|rejected|ruled out|ADR-\d+)\b",
    re.IGNORECASE,
)
_OPEN = re.compile(
    r"\b(TODO|FIXME|next steps?|still (?:need|to)|not yet|open questions?|follow[- ]?ups?|"
    r"blocked|remaining|left to do|need to)\b",
    re.IGNORECASE,
)
_SENTENCE = re.compile(r"(?<=[.!?])\s+|\n+")
_PREAMBLE = {
    "claude-code": (
        "Paste this as the first message of a new Claude Code session (or save it as "
        "HANDOFF.md). With the ctx MCP server configured, drill into any `[E<id>]` via "
        "the `get_session` / `get_context` tools."
    ),
    "codex": (
        "Give this to Codex as starting context (for example save it as HANDOFF.md and "
        "reference it from your first prompt). `[E<id>]` are ctx event ids."
    ),
    "generic": "Context brief generated by ctx. `[E<id>]` are ctx event ids (see Citations).",
}


def _clip(text: str, n: int = LINE_CHARS) -> str:
    text = " ".join(text.split())
    return text if len(text) <= n else text[: n - 1] + "…"


def _stamp(ms: int) -> str:
    return datetime.fromtimestamp(ms / 1000, UTC).strftime("%Y-%m-%d %H:%M")


def _matching(items: list[ContextItem], pattern: re.Pattern) -> list[tuple[int, str]]:
    """Newest MAX_BULLETS distinct matching sentences from text events, chronological."""
    found: dict[str, int] = {}
    for item in items:
        if item.type != "text":
            continue
        for sentence in _SENTENCE.split(item.text):
            sentence = sentence.strip().lstrip("-*#> ").strip()
            if len(sentence) >= 12 and pattern.search(sentence):
                found.pop(_clip(sentence), None)
                found[_clip(sentence)] = item.evidence_event_ids[0]
    return [(eid, s) for s, eid in list(found.items())[-MAX_BULLETS:]]


def _top(counter: Counter, n: int = 8) -> list[tuple[str, int]]:
    return sorted(counter.items(), key=lambda kv: (-kv[1], kv[0]))[:n]


def collect(
    conn: sqlite3.Connection,
    project: str | None = None,
    since: int | None = None,
    budget: int = DEFAULT_BUDGET,
    *,
    include_all: bool = False,
    exclude_mcp: bool = False,
) -> ContextPackage:
    """The evidence for a handoff: newest events, chronological, via build_context."""
    return build_context(
        conn,
        "",
        budget,
        project,
        since=since,
        include_all=include_all,
        exclude_mcp=exclude_mcp,
        top_n=MAX_ITEMS,
    )


def render_handoff(conn: sqlite3.Connection, package: ContextPackage, to: str = "generic") -> str:
    if to not in TARGETS:
        raise ValueError(f"unknown target {to!r}; use one of: {', '.join(TARGETS)}")
    name = "all allowed projects"
    if package.project:
        row = conn.execute(
            "SELECT name FROM projects WHERE id = ?", (resolve_project(conn, package.project),)
        ).fetchone()
        name = row["name"]
    out = [f"# Handoff: {name}", "", _PREAMBLE[to], ""]
    items = package.items
    if not items:
        out += ["No activity found for this scope and window.", ""]
        return redact("\n".join(out))
    first, last = items[0].citation.ts, items[-1].citation.ts
    out.append(
        f"_{len(items)} events, {_stamp(first)} to {_stamp(last)} UTC; extractive (no LLM); "
        f"{len(package.left_out)} older events left out by the token budget._"
    )

    sessions: dict[str, list] = {}
    for it in items:
        sid = it.citation.session_id
        if sid and it.type == "text":
            sessions.setdefault(sid, [it.citation.source, 0])[1] += 1
    titles = {
        r["id"]: r["title"]
        for r in conn.execute(
            f"SELECT id, title FROM sessions WHERE id IN ({','.join('?' * len(sessions))})",
            list(sessions),
        )
    }
    out += ["", "## State"]
    for sid, (src, n) in sorted(sessions.items()):
        title = redact(titles.get(sid) or "") or "-"
        out.append(f"- {src} session `{sid}`: {title} ({n} messages)")
    texts = [i for i in items if i.type == "text"]
    last_user = next((i for i in reversed(texts) if i.role == "user"), None)
    last_asst = next((i for i in reversed(texts) if i.role == "assistant"), None)
    if last_user:
        out.append(
            f"- Last request: {_clip(last_user.text, 400)} [E{last_user.evidence_event_ids[0]}]"
        )
    if last_asst:
        eid = last_asst.evidence_event_ids[0]
        out.append(f"- Where it left off: {_clip(last_asst.text, 400)} [E{eid}]")

    for heading, pattern in (("Decisions (candidates)", _DECISION), ("Open threads", _OPEN)):
        out += ["", f"## {heading}"]
        rows = _matching(items, pattern)
        out += [f"- {s} [E{eid}]" for eid, s in rows] or ["- none detected"]

    files: Counter = Counter()
    commands: Counter = Counter()
    for it in items:
        if it.type.startswith("tool:"):
            fs, cs = tool_targets(it.text)
            files.update(_clip(f, 120) for f in fs)
            commands.update(_clip(c.strip().splitlines()[0], 80) for c in cs if c.strip())
    out += ["", "## Recent files"]
    out += [f"- `{f}` ({n}x)" for f, n in _top(files)] or ["- none"]
    out += ["", "## Recent commands"]
    out += [f"- `{c}` ({n}x)" for c, n in _top(commands)] or ["- none"]

    cited = sorted(set(_cited_ids("\n".join(out))))
    by_id = {i.citation.event_id: i.citation for i in items}
    out += ["", "## Citations"]
    for eid in cited:
        c = by_id.get(eid)
        if c:
            out.append(
                f"- [E{eid}] {c.source} session={c.source_session_id or '-'} "
                f"message={c.message_id or '-'} {_stamp(c.ts)}"
            )
    return redact("\n".join(out)) + "\n"


def _cited_ids(text: str) -> list[int]:
    return [int(m) for m in re.findall(r"\[E(\d+)\]", text)]
